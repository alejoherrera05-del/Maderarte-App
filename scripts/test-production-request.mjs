import assert from 'node:assert/strict';
import { buildProductionRequest as build, productionEligibility as eligibility, supplierWhatsAppUrl } from '../public/js/core/production-request.js';
const order = { number:'MP-OP-0001',status:'CONFIRMADA',client:'CLIENTE PRIVADO',document:'DOCUMENTO PRIVADO',phone:'CONTACTO PRIVADO',paid:876543,total:987654,notes:'NOTA PRIVADA',pdfUrl:'https://example.invalid/private' };
const item = { id:'i1',description:'Sofá',quantity:3,delivered:1,cancelled:0,pending:2,fulfillment:'PARA_SOLICITAR',agreement:'SEPARADO',fabricColor:'Lino gris',woodColor:'Roble',measures:'200 cm',specifications:'Brazo recto',unit:'UN',unitValue:987654 };
const input = { order,items:[item],selected:[{id:'i1',quantity:1}],priorReview:true,customerNotice:true };
const text = build(input);
assert.match(text,/Lino gris/);assert.match(text,/Cantidad: 1 UN/);assert.match(text,/Popayán/);
for (const secret of ['CLIENTE PRIVADO','DOCUMENTO PRIVADO','CONTACTO PRIVADO','NOTA PRIVADA','987654','876543','https://example.invalid/private']) assert.ok(!text.includes(secret));
assert.throws(()=>build({...input,customerNotice:false}),/avisó/);
assert.throws(()=>build({...input,priorReview:false}),/solicitudes previas/);
for (const quantity of [0,-1,1.5,3,NaN]) assert.throws(()=>build({...input,selected:[{id:'i1',quantity}]}));
assert.throws(()=>build({...input,selected:[{id:'otro',quantity:1}]}));
assert.throws(()=>build({...input,selected:[...input.selected,...input.selected]}));
assert.throws(()=>build({...input,order:{...order,status:'ANULADA'}}));
assert.ok(eligibility(order,{...item,pending:3}));
assert.ok(eligibility(order,{...item,fulfillment:'DISPONIBLE'}));
assert.ok(eligibility(order,{...item,fulfillment:'POR_DEFINIR'}));
assert.equal(item.pending,2);assert.equal(order.paid,876543);
const url = new URL(supplierWhatsAppUrl('300 000 0000',text));
assert.equal(url.hostname,'wa.me');assert.equal(url.pathname,'/573000000000');assert.equal(url.searchParams.get('text'),text);
assert.throws(()=>supplierWhatsAppUrl('javascript:alert(1)',text));
assert.equal(new URL(supplierWhatsAppUrl('',text)).pathname,'/');
console.log('Production request: selection, separated notice, privacy and manual WhatsApp checks passed.');
