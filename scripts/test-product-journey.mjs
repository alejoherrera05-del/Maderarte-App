import assert from 'node:assert/strict';
import { productState, journeySteps } from '../public/js/core/product-journey.js';
import { supplierDirectory } from '../public/js/core/supplier-directory.js';
const order={number:'QA-OP-1',status:'CONFIRMADA'},item={id:'a',quantity:1,pending:1,delivered:0,cancelled:0,fulfillment:'PARA_SOLICITAR',agreement:'ENTREGA_POSTERIOR'};
assert.equal(productState(item,order).label,'Por solicitar a fábrica');
assert.match(journeySteps(item,order).find(s=>s.label==='Confirmación y fabricación').detail,/Sin confirmación registrada/);
assert.equal(journeySteps(item,order).filter(s=>s.done).length,1);
assert.equal(productState({...item,agreement:'SEPARADO'},order).label,'Separado · requiere fábrica');
assert.equal(productState({...item,agreement:'SEPARADO',fulfillment:'DISPONIBLE'},order).label,'Separado');
assert.equal(productState({...item,delivered:1,pending:0},order).label,'Despachado');
assert.match(productState({...item,delivered:1,pending:0},order).note,/No confirma recepción/);
assert.equal(productState(item,{...order,status:'ANULADA'}).label,'Anulado');
assert.equal(journeySteps({...item,cancelled:1},order).length,1);
const map=new Map(),storage={getItem:k=>map.get(k),setItem:(k,v)=>map.set(k,v)};
const first=supplierDirectory(storage,'one:trial'),second=supplierDirectory(storage,'two:trial');
first.save({name:' Taller   ejemplo ',phone:'+57 300 000 0000',favorite:true});
assert.equal(first.list()[0].name,'Taller ejemplo');assert.equal(second.list().length,0);
first.save({name:'TALLER EJEMPLO',phone:'',favorite:false});assert.equal(first.list().length,1);assert.equal(first.list()[0].favorite,false);
assert.throws(()=>first.save({name:'',phone:'',favorite:false}));
assert.throws(()=>first.save({name:'Taller',phone:'javascript:bad',favorite:false}));
console.log('Product journey and supplier isolation verified.');
